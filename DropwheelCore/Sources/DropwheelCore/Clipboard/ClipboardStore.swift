import CryptoKit
import Foundation

/// Запись истории буфера обмена.
public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable { case text, image, files }

    public let id: UUID
    public let kind: Kind
    /// Текст (для .text).
    public let text: String?
    /// Пути файлов (для .files).
    public let paths: [String]?
    /// Имя PNG-файла в папке истории (для .image).
    public let imageFile: String?
    public let pixelWidth: Int?
    public let pixelHeight: Int?
    /// Хэш содержимого: одинаковое содержимое не дублируется, а поднимается наверх.
    public let digest: String
    public var date: Date
    public var pinned: Bool
    /// Откуда скопировано (bundle id и имя приложения).
    public let sourceBundleID: String?
    public let sourceName: String?

    /// «2 файла», «5 файлов», «21 файл».
    static func files(_ n: Int) -> String {
        let mod10 = n % 10, mod100 = n % 100
        let word = mod10 == 1 && mod100 != 11 ? "файл"
            : (2...4).contains(mod10) && !(12...14).contains(mod100) ? "файла" : "файлов"
        return "\(n) \(word)"
    }

    /// Строка для поиска и заголовка в списке.
    public var title: String {
        switch kind {
        case .text:
            let line = (text ?? "").split(whereSeparator: \.isNewline).first.map(String.init) ?? ""
            return line.trimmingCharacters(in: .whitespaces)
        case .files:
            let names = (paths ?? []).map { ($0 as NSString).lastPathComponent }
            return names.count == 1 ? names[0] : "\(Self.files(names.count)): \(names.prefix(3).joined(separator: ", "))"
        case .image:
            if let w = pixelWidth, let h = pixelHeight { return "Изображение \(w) × \(h)" }
            return "Изображение"
        }
    }
}

/// История буфера обмена на диске: index.json и PNG-картинки в одной папке.
/// Без UI и без NSPasteboard — их держит приложение; здесь только данные и правила.
public final class ClipboardStore {
    public private(set) var items: [ClipItem] = []
    /// Сколько незакреплённых записей хранить.
    public var limit: Int { didSet { trim(); save() } }

    /// Самый длинный текст, который сохраняем (символов).
    public static let maxTextLength = 500_000
    /// Самая большая картинка, которую сохраняем (байт PNG).
    public static let maxImageBytes = 25 * 1024 * 1024

    /// Типы, которыми менеджеры паролей и системные утилиты помечают то, что нельзя хранить
    /// (соглашение nspasteboard.org и типы конкретных приложений).
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Не сохранять содержимое с такими типами (пароли, временные данные).
    public static func shouldIgnore(types: [String]) -> Bool {
        types.contains { ignoredTypes.contains($0) }
    }

    private let directory: URL
    private var indexURL: URL { directory.appendingPathComponent("index.json") }

    public init(directory: URL, limit: Int = 200) {
        self.directory = directory
        self.limit = limit
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: indexURL),
           let decoded = try? JSONDecoder.iso.decode([ClipItem].self, from: data) {
            items = decoded
        }
    }

    public func imageURL(for item: ClipItem) -> URL? {
        item.imageFile.map { directory.appendingPathComponent($0) }
    }

    // MARK: - Добавление

    @discardableResult
    public func addText(_ text: String, source: (id: String?, name: String?) = (nil, nil), date: Date = Date()) -> ClipItem? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maxTextLength else { return nil }
        let digest = Self.digest("text", Data(text.utf8))
        return insert(digest: digest, date: date) {
            ClipItem(id: UUID(), kind: .text, text: text, paths: nil, imageFile: nil, pixelWidth: nil, pixelHeight: nil,
                     digest: digest, date: date, pinned: false, sourceBundleID: source.id, sourceName: source.name)
        }
    }

    @discardableResult
    public func addFiles(_ urls: [URL], source: (id: String?, name: String?) = (nil, nil), date: Date = Date()) -> ClipItem? {
        let paths = urls.filter(\.isFileURL).map(\.path)
        guard !paths.isEmpty else { return nil }
        let digest = Self.digest("files", Data(paths.joined(separator: "\n").utf8))
        return insert(digest: digest, date: date) {
            ClipItem(id: UUID(), kind: .files, text: nil, paths: paths, imageFile: nil, pixelWidth: nil, pixelHeight: nil,
                     digest: digest, date: date, pinned: false, sourceBundleID: source.id, sourceName: source.name)
        }
    }

    /// `png` — уже закодированная картинка; размеры — в пикселях.
    @discardableResult
    public func addImage(png: Data, width: Int, height: Int, source: (id: String?, name: String?) = (nil, nil), date: Date = Date()) -> ClipItem? {
        guard !png.isEmpty, png.count <= Self.maxImageBytes else { return nil }
        let digest = Self.digest("image", png)
        return insert(digest: digest, date: date) {
            let name = "\(digest.prefix(24)).png"
            do { try png.write(to: directory.appendingPathComponent(name), options: .atomic) } catch { return nil }
            return ClipItem(id: UUID(), kind: .image, text: nil, paths: nil, imageFile: name, pixelWidth: width, pixelHeight: height,
                            digest: digest, date: date, pinned: false, sourceBundleID: source.id, sourceName: source.name)
        }
    }

    /// Повтор того же содержимого поднимает существующую запись наверх (и сохраняет закрепление).
    private func insert(digest: String, date: Date, make: () -> ClipItem?) -> ClipItem? {
        if let i = items.firstIndex(where: { $0.digest == digest }) {
            var existing = items.remove(at: i)
            existing.date = date
            items.insert(existing, at: 0)
            save()
            return existing
        }
        guard let item = make() else { return nil }
        items.insert(item, at: 0)
        trim()
        save()
        return item
    }

    // MARK: - Изменение

    /// Поднять запись наверх (после того как её снова положили в буфер).
    public func touch(_ id: UUID, date: Date = Date()) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        var item = items.remove(at: i)
        item.date = date
        items.insert(item, at: 0)
        save()
    }

    public func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        trim()
        save()
    }

    public func remove(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        deleteFiles(of: items.remove(at: i))
        save()
    }

    /// Очистить историю; закреплённое остаётся, если не попросили обратное.
    public func clear(keepPinned: Bool = true) {
        let (kept, gone) = items.reduce(into: ([ClipItem](), [ClipItem]())) { acc, item in
            if keepPinned && item.pinned { acc.0.append(item) } else { acc.1.append(item) }
        }
        gone.forEach(deleteFiles)
        items = kept
        save()
    }

    // MARK: - Поиск

    /// Закреплённые сверху, дальше по времени. Поиск без учёта регистра по тексту, именам файлов и приложению.
    public func search(_ query: String) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let ordered = items.filter(\.pinned) + items.filter { !$0.pinned }
        guard !q.isEmpty else { return ordered }
        return ordered.filter { item in
            let haystack = [item.text, item.paths?.joined(separator: " "), item.sourceName, item.kind == .image ? item.title : nil]
                .compactMap { $0 }
            return haystack.contains { $0.localizedCaseInsensitiveContains(q) }
        }
    }

    // MARK: - Внутреннее

    /// Лишние незакреплённые записи удаляются с конца вместе с картинками.
    private func trim() {
        var unpinned = 0
        var kept: [ClipItem] = []
        for item in items {
            if item.pinned { kept.append(item); continue }
            unpinned += 1
            if unpinned <= max(limit, 0) { kept.append(item) } else { deleteFiles(of: item) }
        }
        items = kept
    }

    private func deleteFiles(of item: ClipItem) {
        if let url = imageURL(for: item) { try? FileManager.default.removeItem(at: url) }
    }

    private func save() {
        guard let data = try? JSONEncoder.iso.encode(items) else { return }
        try? data.write(to: indexURL, options: .atomic)
    }

    static func digest(_ kind: String, _ data: Data) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(kind.utf8))
        hasher.update(data: data)
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

private extension JSONEncoder {
    static var iso: JSONEncoder { let e = JSONEncoder(); e.dateEncodingStrategy = .iso8601; return e }
}

private extension JSONDecoder {
    static var iso: JSONDecoder { let d = JSONDecoder(); d.dateDecodingStrategy = .iso8601; return d }
}
